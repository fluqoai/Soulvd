import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const db = new PGlite();
const actor = '00000000-0000-4000-8000-000000000001';
const merchant = '00000000-0000-4000-8000-000000000002';
const tenant = '10000000-0000-4000-8000-000000000001';
try {
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
  create schema auth; create function auth.uid() returns uuid language sql as $$ select null::uuid $$;
  create table auth.users(id uuid primary key,email text,raw_user_meta_data jsonb);
  create table public.users(id uuid primary key,email text,full_name text,role text constraint users_role_check check(role in ('owner','editor')));
  create function public.tg_handle_new_user() returns trigger language plpgsql as $$ begin return new; end $$;`);
  await db.exec(await readFile(new URL('../supabase/migrations/20260916084850_merchant_subscriptions.sql', import.meta.url), 'utf8'));
  await db.exec(`alter table public.tenants add column is_test boolean not null default false;
  insert into public.users values('${actor}','owner@test.invalid','Owner','owner'),('${merchant}','client@test.invalid','Client','merchant');
  insert into public.tenants(id,name) values('${tenant}','Client');
  insert into public.subscriptions values('${tenant}','starter_v1','pending',now(),now()+interval '1 month');
  grant select on public.users to service_role;`);
  await db.exec(await readFile(new URL('../supabase/migrations/20260917180128_manual_bank_transfers.sql', import.meta.url), 'utf8'));
  await db.exec('set role service_role');
  const confirm = (reference, amount, purpose = 'subscription', user = actor) => db.query('select public.soulvd_confirm_bank_transfer($1,$2,$3,$4,$5)', [user, tenant, reference, amount, purpose]);
  await assert.rejects(confirm('bad-owner',29900,'subscription',merchant), /FORBIDDEN/);
  await assert.rejects(confirm('wrong-amount',39900), /AMOUNT_MISMATCH/);
  await confirm('bank-001',29900);
  const before = (await db.query('select * from public.subscriptions')).rows[0];
  assert.equal(before.status,'active');
  await confirm('bank-001',29900);
  assert.deepEqual((await db.query('select * from public.subscriptions')).rows[0],before);
  await assert.rejects(confirm('bank-001',39900),/REFERENCE_ALREADY_USED/);
  await assert.rejects(confirm('early-renew',29900),/CYCLE_STILL_ACTIVE/);
  await confirm('upgrade-001',10000,'upgrade');
  const after = (await db.query('select * from public.subscriptions')).rows[0];
  assert.equal(after.plan_id,'pro_growth_v1');
  assert.equal(after.period_start.getTime(),before.period_start.getTime());
  assert.equal(after.period_end.getTime(),before.period_end.getTime());
  await assert.rejects(confirm('duplicate-upgrade',10000,'upgrade'),/UPGRADE_NOT_AVAILABLE/);
  await db.exec(`reset role; update public.tenants set is_test=true; set role service_role;`);
  await assert.rejects(confirm('test-payment',39900),/TEST_WORKSPACE/);
  await db.exec(`reset role; update public.tenants set is_test=false; update public.subscriptions set period_start=now()-interval '2 months',period_end=now()-interval '1 month'; set role service_role;`);
  await confirm('renew-001',39900);
  const renewed = (await db.query('select * from public.subscriptions')).rows[0];
  assert.equal(renewed.status,'active');
  assert.ok(renewed.period_start.getTime()>before.period_start.getTime());
  assert.equal((await db.query('select count(*)::integer as count from soulvd_private.bank_transfers')).rows[0].count,3);
  await db.exec('reset role');
  for (const role of ['anon','authenticated']) assert.equal((await db.query("select has_function_privilege($1,'public.soulvd_confirm_bank_transfer(uuid,uuid,text,integer,text)','execute') as allowed",[role])).rows[0].allowed,false);
  console.log('PASS: bank confirmation authorization, exact amounts, replay protection, cycle boundaries and upgrade preservation');
} finally { await db.close(); }
